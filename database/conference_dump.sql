CREATE VIEW public.accepted_paper_schedule AS
 SELECT p.paper_id,
    p.title AS paper_title,
    c.conference_id,
    c.acronym,
    t.name AS track_name,
    s.session_id,
    s.title AS session_title,
    s.session_date,
    s.start_time,
    s.end_time,
    s.room_label,
    (((ch.given_name)::text || ' '::text) || (ch.surname)::text) AS chair_name,
    (((au.given_name)::text || ' '::text) || (au.surname)::text) AS corresponding_author,
    au.email AS corresponding_email
   FROM ((((((public.paper p
     JOIN public.conference_session s ON ((s.session_id = p.session_id)))
     JOIN public.conference c ON ((c.conference_id = s.conference_id)))
     JOIN public.track t ON ((t.track_id = p.track_id)))
     JOIN public.app_user ch ON ((ch.user_id = s.chair_id)))
     LEFT JOIN public.paper_author pa ON (((pa.paper_id = p.paper_id) AND (pa.is_corresponding = true))))
     LEFT JOIN public.app_user au ON ((au.user_id = pa.author_id)))
  WHERE ((p.status)::text = 'accepted'::text);


